from datetime import datetime, timedelta

import pytest

from giveaway_bot import rules
from giveaway_bot.config import Sweepstake
from giveaway_bot.discovery import parse_feed
from giveaway_bot.filler import classify
from giveaway_bot.runner import enter_one
from giveaway_bot.tracker import Tracker



# ---------- pure unit tests ----------

def test_rules_detect_automation_ban():
    assert rules.automation_banned("Entries generated by script or automated means are void.")
    assert rules.automation_banned("Use of any automated entry method is prohibited.")
    assert not rules.automation_banned("One entry per person per day. Must be 18 or older.")


def test_rules_success_and_age():
    assert rules.looks_successful("Thanks for entering! Good luck.")
    assert not rules.looks_successful("Please fill in all fields")
    assert rules.minimum_age("must be 21 years of age or older") == 21


def _f(**kw):
    base = dict(type="text", tag="input", name="", id="", autocomplete="", placeholder="",
                aria="", label="", required=False, maxlength=None, options=None)
    base.update(kw)
    return base


def test_classify():
    assert classify(_f(name="fname")) == "first_name"
    assert classify(_f(name="lastName")) == "last_name"
    assert classify(_f(type="email")) == "email"
    assert classify(_f(placeholder="ZIP")) == "zip"
    assert classify(_f(name="dob_month")) == "birth_month"
    assert classify(_f(autocomplete="address-level1")) == "state"
    assert classify(_f(name="essay", label="Favorite recipe?")) is None


def test_tracker_frequency(tmp_path):
    t = Tracker(tmp_path / "db.sqlite")
    assert t.is_due("u", "daily")
    t.record("u", "entered")
    assert not t.is_due("u", "daily")
    assert t.is_due("u", "daily", now=datetime.now() + timedelta(hours=24))
    t.record("o", "needs_manual")
    assert not t.is_due("o", "once")


def test_parse_feed():
    rss = "<rss><channel><item><title>Win A</title><link>https://a.example/x</link></item></channel></rss>"
    atom = ('<feed xmlns="http://www.w3.org/2005/Atom"><entry><title>B</title>'
            '<link href="https://b.example/y"/></entry></feed>')
    assert parse_feed(rss) == [("Win A", "https://a.example/x")]
    assert parse_feed(atom) == [("B", "https://b.example/y")]


# ---------- browser tests against local fixture pages ----------

@pytest.mark.parametrize("page,expected,why", [
    ("good.html", "entered", "confirmation"),
    ("banned.html", "needs_manual", "prohibit"),
    ("linked_rules.html", "needs_manual", "prohibit"),
    ("captcha.html", "needs_manual", "CAPTCHA"),
    ("ended.html", "skipped", "ended"),
    ("unknown_required.html", "needs_manual", "could not fill"),
])
def test_enter_pages(server, ctx, cfg, page, expected, why):
    status, detail = enter_one(ctx, cfg, Sweepstake(url=f"{server}/{page}"))
    assert status == expected, detail
    assert why in detail


def test_good_form_values_and_no_marketing(server, ctx, cfg):
    """Check what was actually put in the form just before submit."""
    from giveaway_bot.filler import fill_form
    page = ctx.new_page()
    page.goto(f"{server}/good.html")
    res = fill_form(page, cfg.profile, Sweepstake(url=""), cfg.settings)
    assert page.input_value("#fn") == "Jane"
    assert page.input_value("[name=contact]") == "jane@example.com"
    assert page.input_value("[name=st]") == "IL"
    assert page.input_value("[name=dob_month]") == "April"
    assert page.input_value("[name=postalCode]") == "62701"
    assert page.is_checked("[name=agree]")
    assert not page.is_checked("[name=news]")
    assert page.input_value("[name=q]") == ""   # search box in another form untouched
    assert not res.unfilled_required
    page.close()
